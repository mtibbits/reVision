"""RELEASING.md names every file that carries the version, and those files agree.

The carrier set is derived, not listed here: tracked files whose text contains the current
version literal, minus the non-carriers below. A file that starts carrying the version fails
until RELEASING.md lists it.

README.md and the CI constraints file must also never name the engine's package in a form that
installs it from PyPI, where it is not published.
"""

from __future__ import annotations

import re
import subprocess
import tomllib
from itertools import takewhile

import revision_engine
from tests.ci_pins import CONSTRAINTS, ROOT

RELEASING = ROOT / "RELEASING.md"
README = ROOT / "README.md"
CARRIERS_HEADING = "## Files that carry the version"
INSTALL_RE = re.compile(
    r"revision-engine @ git\+https://github\.com/mtibbits/reVision@v(\d+\.\d+\.\d+)"
)
# Any mention of the package name, spelled as pip would normalise it (case, -, _, .), that is not
# the by-tag "@ git+" form installs from PyPI. A module path (name followed by / or . and a word
# character) is not an install.
BARE_NAME_RE = re.compile(r"(?i)\brevision[-_.]engine\b(?![./]\w)(?!\s*@\s*git\+)")
PYPI_GUARDED = (README, CONSTRAINTS)
# Path prefixes of tracked files that are never carriers.
NON_CARRIERS = (
    # Pins third-party packages; a pin may share the engine's version string by chance.
    CONSTRAINTS.relative_to(ROOT).as_posix(),
    # Built example output; regenerated by the golden test, never bumped by hand.
    "tests/golden/",
)


def _version_literal(version: str) -> re.Pattern[str]:
    # A dot next to the version is a version-part separator only when a digit is beyond it,
    # so "X.Y.Z." at the end of a sentence matches and "X.Y.Z.1" does not.
    return re.compile(r"(?<!\d\.)(?<!\d)" + re.escape(version) + r"(?!\.?\d)")


def _carriers(version: str) -> set[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True
    ).stdout.decode("utf-8")
    literal = _version_literal(version)
    found = set()
    for path in filter(None, out.split("\0")):
        if path.startswith(NON_CARRIERS):
            continue
        try:
            text = (ROOT / path).read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        if literal.search(text):
            found.add(path)
    return found


def _listed() -> set[str]:
    lines = RELEASING.read_text(encoding="utf-8").splitlines()
    assert CARRIERS_HEADING in lines, f"RELEASING.md has no heading {CARRIERS_HEADING!r}"
    after = lines[lines.index(CARRIERS_HEADING) + 1 :]
    section = takewhile(lambda line: not line.startswith("## "), after)
    # The first backticked span of each bullet is the path; later spans show the line's form.
    return {m.group(1) for line in section if (m := re.match(r"- `([^`]+)`", line))}


def test_version_literal_matches_the_version_not_its_neighbours():
    # Not the engine's version, or this file would itself be a carrier.
    literal = _version_literal("9.8.7")
    for text in ("v9.8.7", "Released 9.8.7.", "ver.9.8.7", "9.8.7,", "9.8.7-rc1", '"9.8.7"'):
        assert literal.search(text), text
    for text in ("9.8.70", "19.8.7", "1.9.8.7", "9.8.7.1"):
        assert not literal.search(text), text


def test_version_sites_agree():
    with (ROOT / "pyproject.toml").open("rb") as f:
        pyproject = tomllib.load(f)
    tags = INSTALL_RE.findall(README.read_text(encoding="utf-8"))
    assert len(tags) == 1, f"README.md has {len(tags)} engine install lines, expected 1: {tags}"
    sites = {
        "pyproject.toml": pyproject["project"]["version"],
        "revision_engine/__init__.py": revision_engine.__version__,
        "README.md install line": tags[0],
    }
    assert len(set(sites.values())) == 1, f"version sites disagree: {sites}"


def test_bare_name_re_flags_pypi_installs_only():
    # Built from PKG so a repo-wide grep for the PyPI install finds only real hits, not this file.
    PKG = "revision-engine"
    for text in (
        f"`pip install {PKG}`",
        f"pip3 install {PKG}.",
        "pip install -c c.txt Revision_Engine",
        f"{PKG}==9.8.7",
        f"python -m pip install '{PKG}'",
    ):
        assert BARE_NAME_RE.search(text), text
    for text in (
        f'pip install "{PKG} @ git+https://github.com/mtibbits/reVision@vX.Y.Z"',
        f'pip install "{PKG} @\n   git+https://github.com/mtibbits/reVision@vX.Y.Z"',
        "revision_engine/static/app.js",
        "revision_engine.__version__",
    ):
        assert not BARE_NAME_RE.search(text), text


def test_docs_do_not_install_from_pypi():
    hits = []
    for path in PYPI_GUARDED:
        # The whole text, not line by line, so "@ git+" wrapped onto the next line still counts.
        text = path.read_text(encoding="utf-8")
        for m in BARE_NAME_RE.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            hits.append(f"{path.relative_to(ROOT).as_posix()}:{line}")
    assert not hits, (
        f"{hits} name the engine's package without the by-tag '@ git+' form, so pip would install "
        "it from PyPI, where the engine is not published (RELEASING.md); point at README's step 1 "
        "instead. Publishing (#56) retires this test."
    )


def test_release_doc_lists_every_version_carrier():
    carriers = _carriers(revision_engine.__version__)
    listed = _listed()
    assert carriers == listed, (
        f"carry the version but not listed in RELEASING.md: {sorted(carriers - listed)}; "
        f"listed but do not carry it: {sorted(listed - carriers)}"
    )
